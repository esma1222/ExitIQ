// Builds the catalogue seed SQL from src/model/catalogue.ts.
import { CATALOGUE_VERSION, PROFILE_WEIGHTS, QUESTIONS } from '../src/model/catalogue';

const lit = (s: string | null | undefined) => (s == null ? 'null' : `'${s.replace(/'/g, "''")}'`);
const json = (v: unknown) => `${lit(JSON.stringify(v))}::jsonb`;
const arr = (xs: string[] | undefined) => (xs && xs.length ? `array[${xs.map(lit).join(', ')}]::text[]` : `'{}'::text[]`);

export function catalogueSql(): string {
  const rows = QUESTIONS.map((q) =>
    `  (${[lit(q.id), lit(CATALOGUE_VERSION), lit(q.domain), q.localWeight, lit(q.route), lit(q.name), lit(q.question),
      json(q.variants ?? {}), json(q.anchors), lit(q.help ?? null), lit(q.evidenceRequest ?? null), lit(q.contributor), arr(q.dependsOn)].join(', ')})`,
  );
  const weights = Object.entries(PROFILE_WEIGHTS).flatMap(([p, ws]) =>
    Object.entries(ws).map(([d, w]) => `  (${lit(CATALOGUE_VERSION)}, ${lit(p)}, ${lit(d)}, ${w})`),
  );
  return `-- GENERATED by \`npm run gen:catalogue-sql\` from src/model/catalogue.ts. Do not edit by hand.
-- ${CATALOGUE_VERSION}: ${QUESTIONS.length} registered controls and the four profile weight matrices.

insert into public.question_definitions
  (id, catalogue_version, domain, local_weight, route, name, question, context_wording, anchors, help, evidence_request, suggested_contributor, depends_on)
values
${rows.join(',\n')}
on conflict (catalogue_version, id) do update set
  domain = excluded.domain, local_weight = excluded.local_weight, route = excluded.route, name = excluded.name,
  question = excluded.question, context_wording = excluded.context_wording, anchors = excluded.anchors, help = excluded.help,
  evidence_request = excluded.evidence_request, suggested_contributor = excluded.suggested_contributor, depends_on = excluded.depends_on;

insert into public.profile_weights (catalogue_version, profile, domain, weight)
values
${weights.join(',\n')}
on conflict (catalogue_version, profile, domain) do update set weight = excluded.weight;
`;
}

