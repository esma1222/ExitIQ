import { useEffect, useState } from 'react';
import { locale, useLang, type Lang } from '../../lib/i18n';
import { requestNarrative, type Narrative as NarrativeData, type ParagraphKind } from '../../lib/narrative';
import { useAssessment } from '../../lib/store';

// Optional written summary on the action plan (brief section 20). It is
// generated asynchronously from the stored result, labelled by statement type,
// and never replaces the deterministic result shown above it.

const TEXT = {
  en: {
    title: 'Written summary',
    intro: 'An optional summary written by AI from your stored result. It uses only your answers and the computed figures above, and it cannot change them.',
    generate: 'Write a summary',
    working: 'Writing your summary. This can take up to a minute.',
    retry: 'Try again',
    kinds: { reported: 'You reported', implication: 'This may imply', next_step: 'Suggested next step' } as Record<ParagraphKind, string>,
    sections: { summary: 'Where preparation stands', strengths: 'Strengths', priorities: 'Priorities', tax: 'Tax preparation' },
    basedOn: (d: string) => `Based on your result of ${d}. Generated by AI; not reviewed by atares. Not legal, tax or financial advice.`,
    stale: 'Your answers have changed since this summary was written. Write a new one to include them.',
    errors: {
      local_only: 'A written summary needs your progress to be saved online. It is currently saved in this browser only.',
      not_saved: 'Your latest result is still being saved. Please try again in a moment.',
      limit: 'You have reached today’s limit for written summaries. The action plan above is complete without it.',
      rejected: 'The summary did not pass our quality checks, so it is not shown. The action plan above is complete without it.',
      unavailable: 'The written summary is not available right now. The action plan above is complete without it.',
    },
  },
  de: {
    title: 'Schriftliche Zusammenfassung',
    intro: 'Eine optionale, von KI verfasste Zusammenfassung Ihres gespeicherten Ergebnisses. Sie stützt sich nur auf Ihre Antworten und die oben berechneten Werte und kann diese nicht verändern.',
    generate: 'Zusammenfassung erstellen',
    working: 'Ihre Zusammenfassung wird erstellt. Das kann bis zu einer Minute dauern.',
    retry: 'Erneut versuchen',
    kinds: { reported: 'Sie haben angegeben', implication: 'Das kann bedeuten', next_step: 'Vorgeschlagener nächster Schritt' } as Record<ParagraphKind, string>,
    sections: { summary: 'Stand der Vorbereitung', strengths: 'Stärken', priorities: 'Prioritäten', tax: 'Steuerliche Vorbereitung' },
    basedOn: (d: string) => `Auf Basis Ihres Ergebnisses vom ${d}. Von KI erstellt, nicht von atares geprüft. Keine Rechts-, Steuer- oder Finanzberatung.`,
    stale: 'Ihre Antworten haben sich seit dieser Zusammenfassung geändert. Erstellen Sie eine neue, um sie einzubeziehen.',
    errors: {
      local_only: 'Für eine schriftliche Zusammenfassung muss Ihr Fortschritt online gespeichert sein. Er ist derzeit nur in diesem Browser gespeichert.',
      not_saved: 'Ihr aktuelles Ergebnis wird noch gespeichert. Bitte versuchen Sie es gleich noch einmal.',
      limit: 'Sie haben das heutige Limit für schriftliche Zusammenfassungen erreicht. Der Maßnahmenplan oben ist auch ohne sie vollständig.',
      rejected: 'Die Zusammenfassung hat unsere Qualitätsprüfung nicht bestanden und wird daher nicht angezeigt. Der Maßnahmenplan oben ist auch ohne sie vollständig.',
      unavailable: 'Die schriftliche Zusammenfassung ist gerade nicht verfügbar. Der Maßnahmenplan oben ist auch ohne sie vollständig.',
    },
  },
} satisfies Record<Lang, unknown>;

type Phase =
  | { k: 'idle' }
  | { k: 'working' }
  | { k: 'done'; data: NarrativeData; forAt: string; lang: Lang }
  | { k: 'error'; reason: keyof (typeof TEXT)['en']['errors'] };

export default function Narrative() {
  const lang = useLang();
  const t = TEXT[lang];
  const s = useAssessment();
  const at = s.lastSnapshot?.at ?? null;
  const [phase, setPhase] = useState<Phase>({ k: 'idle' });

  // A narrative in another language is not shown; the user can write a new one.
  useEffect(() => {
    if (phase.k === 'done' && phase.lang !== lang) setPhase({ k: 'idle' });
  }, [lang, phase]);

  const run = async () => {
    setPhase({ k: 'working' });
    const r = await requestNarrative(s.remoteId, at, lang);
    setPhase(r.ok ? { k: 'done', data: r.narrative, forAt: at ?? '', lang } : { k: 'error', reason: r.reason });
  };

  const dateLabel = (iso: string) => {
    const d = new Date(iso);
    return Number.isNaN(d.getTime()) ? '' : d.toLocaleString(locale(lang), { day: 'numeric', month: 'long', year: 'numeric', hour: '2-digit', minute: '2-digit' });
  };

  return (
    <section aria-labelledby="narrative-title" aria-busy={phase.k === 'working'} style={{ display: 'flex', flexDirection: 'column', gap: 14 }}>
      <h2 className="h3" id="narrative-title">{t.title}</h2>
      <p style={{ margin: 0, fontSize: 14, lineHeight: 1.6, color: 'var(--grey-4)', maxWidth: 820 }}>{t.intro}</p>

      {phase.k === 'idle' && (
        <button type="button" className="btn btn-navy" style={{ alignSelf: 'flex-start' }} onClick={run}>{t.generate}</button>
      )}
      {phase.k === 'working' && <p role="status" style={{ margin: 0, fontSize: 14 }}>{t.working}</p>}
      {phase.k === 'error' && (
        <div role="status" style={{ display: 'flex', gap: 12, alignItems: 'center', flexWrap: 'wrap', fontSize: 14 }}>
          <span>{t.errors[phase.reason]}</span>
          {phase.reason !== 'limit' && phase.reason !== 'local_only' && (
            <button type="button" className="btn btn-sm btn-outline" onClick={run}>{t.retry}</button>
          )}
        </div>
      )}
      {phase.k === 'done' && (
        <article style={{ display: 'flex', flexDirection: 'column', gap: 22, padding: 24, borderRadius: 20, background: 'var(--grey-1)' }}>
          {(['summary', 'strengths', 'priorities', 'tax'] as const).map((key) => (
            <div key={key} style={{ display: 'flex', flexDirection: 'column', gap: 10 }}>
              <h3 style={{ margin: 0, fontSize: 16, fontWeight: 700 }}>{t.sections[key]}</h3>
              {phase.data[key].map((p, i) => (
                <p key={i} style={{ margin: 0, fontSize: 15, lineHeight: 1.65 }}>
                  <span className="pill" style={{ marginRight: 8, fontSize: 11, background: p.kind === 'next_step' ? 'var(--navy-2)' : 'var(--white)', color: p.kind === 'next_step' ? 'var(--white)' : 'var(--navy)', border: '1px solid var(--grey-2)' }}>{t.kinds[p.kind]}</span>
                  {p.text}
                  {p.question_ids.length > 0 && <span style={{ color: 'var(--grey-4)', fontSize: 12 }}> ({p.question_ids.join(', ')})</span>}
                </p>
              ))}
            </div>
          ))}
          <p style={{ margin: 0, fontSize: 12, color: 'var(--grey-4)' }}>{t.basedOn(dateLabel(phase.forAt))}</p>
          {phase.forAt !== at && (
            <div style={{ display: 'flex', gap: 12, alignItems: 'center', flexWrap: 'wrap', fontSize: 14 }}>
              <span>{t.stale}</span>
              <button type="button" className="btn btn-sm btn-outline" onClick={run}>{t.generate}</button>
            </div>
          )}
        </article>
      )}
    </section>
  );
}
